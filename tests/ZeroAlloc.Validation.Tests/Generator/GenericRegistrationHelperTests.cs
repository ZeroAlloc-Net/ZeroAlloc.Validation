namespace ZeroAlloc.Validation.Tests.Generator;

/// <summary>
/// Issue #238, phase 2: a generic <c>[Validate]</c> model gets a registration helper generic over
/// its type parameters, <c>services.AddPageValidator&lt;Customer&gt;()</c>, in a static class in
/// the model's namespace, and a <c>ValidateWithZeroAlloc&lt;…&gt;()</c> overload that inference
/// closes from the options builder. Both register the model's validator and every validator it
/// takes, closed at the call site. Every source here is compiled with the generated files, so an
/// error or warning in generated code fails the test.
/// </summary>
public class GenericRegistrationHelperTests
{
    private const string PageModels = """
        using System.Collections.Generic;
        using ZeroAlloc.Validation;
        namespace Ns;

        public class Customer { }

        [Validate]
        public class Page<TItem> where TItem : class
        {
            [NotEmpty] public string Title { get; set; } = "";
            public List<Line<TItem>> Lines { get; set; } = new();
        }

        [Validate]
        public class Line<TItem> where TItem : class
        {
            [GreaterThan(0)] public int Quantity { get; set; }
            [NotNull] public TItem? Item { get; set; }
        }
        """;

    private const string HelperHint = "Ns.ZeroAllocGenericValidatorRegistrationExtensions.g.cs";

    [Fact]
    public void GenericModel_GetsARegistrationHelperInItsNamespace()
    {
        var output = GenericModelTestHost.Run(PageModels).Compiles();

        Assert.Equal(
            """
            // <auto-generated />
            #nullable enable

            using Microsoft.Extensions.DependencyInjection;
            using Microsoft.Extensions.DependencyInjection.Extensions;

            namespace Ns;

            /// <summary>Registers the generated validators of the generic models in this namespace, closed over the type arguments of each call.</summary>
            public static class ZeroAllocGenericValidatorRegistrationExtensions
            {
                /// <summary>Registers the validator of <c>Page</c> closed over the given type arguments, and every validator it takes.</summary>
                /// <typeparam name="TItem">The type argument for the <c>TItem</c> type parameter of <c>Page</c>.</typeparam>
                /// <param name="services">The service collection to add the registrations to.</param>
                /// <returns>The same service collection, so calls can be chained.</returns>
                public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddPageValidator<TItem>(
                    this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)
                    where TItem : class
                {
                    services.TryAddSingleton<global::ZeroAlloc.Validation.ValidatorFor<global::Ns.Page<TItem>>, global::Ns.PageValidator<TItem>>();
                    services.TryAddEnumerable(global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Singleton<global::ZeroAlloc.Validation.IModelValidator, global::ZeroAlloc.Validation.ValidatorFor<global::Ns.Page<TItem>>>(static sp => global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<global::ZeroAlloc.Validation.ValidatorFor<global::Ns.Page<TItem>>>(sp)));
                    services.TryAddSingleton<global::ZeroAlloc.Validation.ValidatorFor<global::Ns.Line<TItem>>, global::Ns.LineValidator<TItem>>();
                    services.TryAddEnumerable(global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Singleton<global::ZeroAlloc.Validation.IModelValidator, global::ZeroAlloc.Validation.ValidatorFor<global::Ns.Line<TItem>>>(static sp => global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<global::ZeroAlloc.Validation.ValidatorFor<global::Ns.Line<TItem>>>(sp)));
                    return services;
                }

                /// <summary>Registers the validator of <c>Line</c> closed over the given type arguments, and every validator it takes.</summary>
                /// <typeparam name="TItem">The type argument for the <c>TItem</c> type parameter of <c>Line</c>.</typeparam>
                /// <param name="services">The service collection to add the registrations to.</param>
                /// <returns>The same service collection, so calls can be chained.</returns>
                public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddLineValidator<TItem>(
                    this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)
                    where TItem : class
                {
                    services.TryAddSingleton<global::ZeroAlloc.Validation.ValidatorFor<global::Ns.Line<TItem>>, global::Ns.LineValidator<TItem>>();
                    services.TryAddEnumerable(global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Singleton<global::ZeroAlloc.Validation.IModelValidator, global::ZeroAlloc.Validation.ValidatorFor<global::Ns.Line<TItem>>>(static sp => global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<global::ZeroAlloc.Validation.ValidatorFor<global::Ns.Line<TItem>>>(sp)));
                    return services;
                }
            }

            """.ReplaceLineEndings("\n"),
            output.Source(HelperHint).ReplaceLineEndings("\n"));
    }

    [Fact]
    public void RegistrationHelper_IsCalledWithTheClosingAsTypeArgument()
    {
