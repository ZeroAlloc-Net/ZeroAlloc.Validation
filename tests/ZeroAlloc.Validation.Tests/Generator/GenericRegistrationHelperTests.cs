    [Fact]
    public void SameNamedModelsInTwoNamespaces_GetAHelperClassEach()
    {
        // One class for both would declare AddBoxValidator<T> twice, CS0111.
        var output = GenericModelTestHost.Run("""
            using ZeroAlloc.Validation;
            namespace A { [Validate] public class Box<T> { [NotEmpty] public string Name { get; set; } = ""; } }
            namespace B { [Validate] public class Box<T> { [NotEmpty] public string Name { get; set; } = ""; } }
            namespace @class.Models { [Validate] public class Crate<T> { [NotEmpty] public string Name { get; set; } = ""; } }
            [Validate] public class Bag<T> { [NotEmpty] public string Name { get; set; } = ""; }

            internal static class Wiring
            {
                public static void Wire(Microsoft.Extensions.DependencyInjection.IServiceCollection services)
                {
                    A.ZeroAllocGenericValidatorRegistrationExtensions.AddBoxValidator<int>(services);
                    B.ZeroAllocGenericValidatorRegistrationExtensions.AddBoxValidator<int>(services);
                    @class.Models.ZeroAllocGenericValidatorRegistrationExtensions.AddCrateValidator<int>(services);
                    services.AddBagValidator<int>();
                }
            }
            """).Compiles();

        Assert.Contains("namespace A;", output.Source("A.ZeroAllocGenericValidatorRegistrationExtensions.g.cs"), StringComparison.Ordinal);
        Assert.Contains("namespace B;", output.Source("B.ZeroAllocGenericValidatorRegistrationExtensions.g.cs"), StringComparison.Ordinal);
        Assert.Contains("namespace @class.Models;", output.Source("class.Models.ZeroAllocGenericValidatorRegistrationExtensions.g.cs"), StringComparison.Ordinal);
        Assert.DoesNotContain("\nnamespace ", output.Source("ZeroAllocGenericValidatorRegistrationExtensions.g.cs").ReplaceLineEndings("\n"), StringComparison.Ordinal);
    }

    [Fact]
    public void InternalGenericModel_GoesInTheInternalHelperClass()
    {
        // The helper's constraint names the internal Base, so a public helper would not compile.
        var output = GenericModelTestHost.Run("""
            using ZeroAlloc.Validation;
            namespace Ns;
            internal class Base { }
            [Validate] public class Box<T> { [NotEmpty] public string Name { get; set; } = ""; }
            [Validate] internal class Crate<T> where T : Base { [NotEmpty] public string Name { get; set; } = ""; }
            public class Outer { [Validate] internal class Inner<T> { [NotEmpty] public string Name { get; set; } = ""; } }
            """).Compiles();

        var helper = output.Source(HelperHint).ReplaceLineEndings("\n");
        var publicClass = helper.IndexOf("public static class ZeroAllocGenericValidatorRegistrationExtensions", StringComparison.Ordinal);
        var internalClass = helper.IndexOf("internal static class InternalZeroAllocGenericValidatorRegistrationExtensions", StringComparison.Ordinal);
        Assert.True(publicClass >= 0 && internalClass > publicClass);
        Assert.Contains("AddBoxValidator<T>(", helper[..internalClass], StringComparison.Ordinal);
        Assert.Contains("AddCrateValidator<T>(", helper[internalClass..], StringComparison.Ordinal);
        Assert.Contains("AddOuter_InnerValidator<T>(", helper[internalClass..], StringComparison.Ordinal);
    }

    [Fact]
    public void TypeParameterNamedLikeAGeneratedIdentifier_GetsAnotherIdentifier()
    {
        // A method cannot declare a parameter, local or lambda parameter named like one of its
        // type parameters, CS0412.
        var output = GenericModelTestHost.Run(
            """
            using ZeroAlloc.Validation;
            namespace Ns;
            [Validate] public class Box<services, sp, builder, services2> where services : class
            {
                [NotEmpty] public string Name { get; set; } = "";
            }

            internal static class Wiring
            {
                public static void Wire(Microsoft.Extensions.DependencyInjection.IServiceCollection services)
                {
                    services.AddBoxValidator<string, int, int, int>();
                    Microsoft.Extensions.DependencyInjection.OptionsServiceCollectionExtensions
                        .AddOptions<Box<string, int, int, int>>(services).ValidateWithZeroAlloc();
                }
            }
            """.Replace("namespace Ns;", "using ZeroAlloc.Validation.Options;\nnamespace Ns;", StringComparison.Ordinal),
            new ValidatorGenerator(), new InjectGenerator(), new OptionsValidationEmitter()).Compiles();

        var helper = output.Source(HelperHint);
        Assert.Contains("IServiceCollection services3)", helper, StringComparison.Ordinal);
        Assert.Contains("static sp2 => ", helper, StringComparison.Ordinal);
        var overload = output.Source("ZeroAlloc.Validation.ZeroAllocOptionsValidationExtensions.g.cs");
        Assert.Contains("> builder2)", overload, StringComparison.Ordinal);
        Assert.Contains("var services3 = builder2.Services;", overload, StringComparison.Ordinal);
    }

