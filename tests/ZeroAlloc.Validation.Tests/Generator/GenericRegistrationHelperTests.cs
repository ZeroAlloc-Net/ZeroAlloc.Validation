    [Fact]
    public void GenericOptionsModelWithAsynchronousRules_ReportsZV0034AtTheCall()
    {
        var output = GenericModelTestHost.Run("""
            using System.Threading;
            using System.Threading.Tasks;
            using ZeroAlloc.Validation;
            using ZeroAlloc.Validation.Options;
            namespace Ns;

            public sealed class SlowAttribute : AsyncValidationAttribute<string?>
            {
                public override ValueTask<bool> IsValidAsync(string? value, CancellationToken ct) => new(true);
            }

            [Validate] public class Box<T> { [Slow] public string Name { get; set; } = ""; }

            internal static class Wiring
            {
                public static void Wire(Microsoft.Extensions.DependencyInjection.IServiceCollection services) =>
                    Microsoft.Extensions.DependencyInjection.OptionsServiceCollectionExtensions
                        .AddOptions<Box<int>>(services).ValidateWithZeroAlloc();
            }
            """,
            new ValidatorGenerator(), new OptionsValidationEmitter());

        var zv0034 = output.OnlyDiagnostic();
        Assert.Equal("ZV0034", zv0034.Id);
        Assert.Contains("'Ns.Box<int>'", zv0034.GetMessage(System.Globalization.CultureInfo.InvariantCulture), StringComparison.Ordinal);
    }
