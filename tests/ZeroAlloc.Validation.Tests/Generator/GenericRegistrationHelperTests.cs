    [Fact]
    public void GenericModelComposingAClosingOfAnother_RegistersItOverTheSameTypeParameters()
    {
        var output = GenericModelTestHost.Run("""
            using System.Collections.Generic;
            using ZeroAlloc.Validation;
            namespace Ns;
            [Validate] public class Address { [NotEmpty] public string City { get; set; } = ""; }
            [Validate] public class Pair<TKey, TValue> { [NotEmpty] public string Name { get; set; } = ""; }
            [Validate]
            public class Catalog<T> where T : Address
            {
                public Pair<T, string>? Pair { get; set; }
                public Pair<int, int>? Fixed { get; set; }
                public T? Home { get; set; }
            }
            """).Compiles();

        var helper = output.Source(HelperHint);
        var start = helper.IndexOf("AddCatalogValidator<T>", StringComparison.Ordinal);
        var catalog = helper[start..helper.IndexOf("return services;", start, StringComparison.Ordinal)];
        Assert.Contains("ValidatorFor<global::Ns.Catalog<T>>, global::Ns.CatalogValidator<T>>();", catalog, StringComparison.Ordinal);
        Assert.Contains("ValidatorFor<global::Ns.Pair<T, string>>, global::Ns.PairValidator<T, string>>();", catalog, StringComparison.Ordinal);
        Assert.Contains("ValidatorFor<global::Ns.Pair<int, int>>, global::Ns.PairValidator<int, int>>();", catalog, StringComparison.Ordinal);
        Assert.Contains("ValidatorFor<global::Ns.Address>, global::Ns.AddressValidator>();", catalog, StringComparison.Ordinal);
    }

    [Fact]
    public void GenericOptionsModel_GetsAnOverloadThatInferenceCloses()
    {
        var output = GenericModelTestHost.Run(
            PageModels.Replace("namespace Ns;", "using ZeroAlloc.Validation.Options;\nnamespace Ns;", StringComparison.Ordinal) + """

            [Validate] public class Settings { [NotEmpty] public string Name { get; set; } = ""; }

            internal static class Wiring
            {
                public static void Wire(Microsoft.Extensions.DependencyInjection.IServiceCollection services)
                {
                    Microsoft.Extensions.DependencyInjection.OptionsServiceCollectionExtensions
                        .AddOptions<Page<Customer>>(services).ValidateWithZeroAlloc();
                    Microsoft.Extensions.DependencyInjection.OptionsServiceCollectionExtensions
                        .AddOptions<Settings>(services).ValidateWithZeroAlloc();
                }
            }
            """,
            new ValidatorGenerator(), new OptionsValidationEmitter()).Compiles();

        var overloads = output.Source("ZeroAlloc.Validation.ZeroAllocOptionsValidationExtensions.g.cs").ReplaceLineEndings("\n");
        Assert.Contains(
            """
                /// <summary>Validates <c>Page</c> with its generated validator whenever the options instance is resolved.</summary>
                /// <typeparam name="TItem">The type argument for the <c>TItem</c> type parameter of <c>Page</c>.</typeparam>
                /// <param name="builder">The options builder to attach validation to.</param>
                /// <returns>The same options builder, so calls can be chained.</returns>
                public static global::Microsoft.Extensions.Options.OptionsBuilder<global::Ns.Page<TItem>> ValidateWithZeroAlloc<TItem>(
                    this global::Microsoft.Extensions.Options.OptionsBuilder<global::Ns.Page<TItem>> builder)
                    where TItem : class
                {
                    var services = builder.Services;
                    services.TryAddSingleton<global::ZeroAlloc.Validation.ValidatorFor<global::Ns.Page<TItem>>, global::Ns.PageValidator<TItem>>();
            """.ReplaceLineEndings("\n"),
            overloads,
            StringComparison.Ordinal);
        Assert.Contains(
            """
                    builder.Services.TryAddSingleton<global::Microsoft.Extensions.Options.IValidateOptions<global::Ns.Page<TItem>>,
                        global::ZeroAlloc.Validation.Options.ZeroAllocOptionsValidator<global::Ns.Page<TItem>>>();
                    return builder;
                }
            """.ReplaceLineEndings("\n"),
            overloads,
            StringComparison.Ordinal);
        Assert.Contains("ValidateWithZeroAlloc(\n        this global::Microsoft.Extensions.Options.OptionsBuilder<global::Ns.Settings> builder)", overloads, StringComparison.Ordinal);
    }

